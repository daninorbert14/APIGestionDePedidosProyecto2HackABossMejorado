-- ==========================================
-- V1__crear_esquema.sql: Crear esquema base
-- ==========================================

-- ==========================================
-- 1. TABLA: terminales
-- ==========================================
CREATE TABLE IF NOT EXISTS terminales (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

-- ==========================================
-- 2. TABLA: categorias
-- ==========================================
CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

-- ==========================================
-- 3. TABLA: productos
-- ==========================================
CREATE TABLE IF NOT EXISTS productos (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    precio DECIMAL(10,2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id)
);

-- ==========================================
-- 4. TABLA: pedidos
-- ==========================================
CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    fecha TIMESTAMP NOT NULL,
    total DECIMAL(10,2) NOT NULL,
    estado_pedido VARCHAR(20) NOT NULL,
    terminal_id BIGINT NOT NULL,
    CONSTRAINT fk_pedido_terminal FOREIGN KEY (terminal_id) REFERENCES terminales(id)
);

-- ==========================================
-- 5. TABLA: pedidos_productos
-- ==========================================
CREATE TABLE IF NOT EXISTS pedidos_productos (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INTEGER NOT NULL,
    precio_unitario DECIMAL(10,2) NOT NULL,
    pedido_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    CONSTRAINT fk_pedido_producto_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id),
    CONSTRAINT fk_pedido_producto_producto FOREIGN KEY (producto_id) REFERENCES productos(id)
);